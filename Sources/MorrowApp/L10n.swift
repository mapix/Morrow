    static var languageCode: String {
        let selected = MorrowLanguage(rawValue: UserDefaults.standard.string(forKey: "SmailPresentationLanguage") ?? "system") ?? .system
        return selected.resolvedCode
    }
    static func t(_ source: String) -> String {
        localized(source, code: languageCode)
    }
    static func localized(_ source: String, code: String) -> String {
        if let value = englishSourceCatalog[source] {
            return code == "zh-Hans" ? value.0 : code == "ja" ? value.1 : source
        }
        guard code != "zh-Hans", let value = catalog[source] else { return source }
        return code == "ja" ? value.1 : value.0
    }
