    /// Only known application status templates are translated. Captured mail
    /// subjects, account names, and diagnostic details remain verbatim.
    static func status(_ source: String, code: String? = nil) -> String {
        let code = code ?? languageCode
        if catalog[source] != nil || englishSourceCatalog[source] != nil { return localized(source, code: code) }
        for template in statusTemplates {
            var pattern = NSRegularExpression.escapedPattern(for: template)
            let count = template.filter { $0 == "{" }.count
            for number in 0..<count { pattern = pattern.replacingOccurrences(of: NSRegularExpression.escapedPattern(for: "{" + String(number) + "}"), with: "(.+)") }
            guard let expression = try? NSRegularExpression(pattern: "^" + pattern + "$"), let match = expression.firstMatch(in: source, range: NSRange(source.startIndex..., in: source)) else { continue }
            let values = (1..<match.numberOfRanges).compactMap { Range(match.range(at: $0), in: source).map { String(source[$0]) } }
            return substitute(localized(template, code: code), values: values)
        }
        return source
    }
    /// Substitution happens after lookup, so user-provided text is never used as
    /// a localization key and languages can reorder the same values.
    static func format(_ source: String, _ values: String...) -> String {
        substitute(t(source), values: values)
    }
    static func substitute(_ template: String, values: [String]) -> String {
        var result = ""; var index = template.startIndex
        while index < template.endIndex {
            if template[index] == "{", let end = template[index...].firstIndex(of: "}"), let number = Int(template[template.index(after: index)..<end]), values.indices.contains(number) {
                result += values[number]; index = template.index(after: end)
            } else { result.append(template[index]); index = template.index(after: index) }
        }
        return result
    }
